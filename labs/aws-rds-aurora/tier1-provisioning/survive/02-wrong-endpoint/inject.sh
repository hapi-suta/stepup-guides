#!/usr/bin/env bash
# survive/02-wrong-endpoint/inject.sh
# Writes a broken endpoint to a simulated application config file.
# This simulates a config deployment that pointed to the wrong host.
#
# Usage:
#   export STUDENT_ENV_FILE=~/.suta/aws-rds-tier1.env
#   bash /Users/hafopezi/Projects/practice/labs/labs/aws-rds-aurora/tier1-provisioning/survive/02-wrong-endpoint/inject.sh

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LAB_DIR="$(dirname "$SCRIPT_DIR")"

source "$LAB_DIR/config.sh"
source "$LAB_DIR/lib/common.sh"

# Path to the simulated app config
APP_CONFIG="/tmp/suta-app-config.env"
BACKUP_CONFIG="/tmp/suta-app-config-backup-02.env"

echo ""
echo "========================================"
echo "  INJECT: Wrong Endpoint"
echo "========================================"
echo ""

# Step 1 - Write the correct config (simulates what was there before)
info "Writing simulated application config..."
cat > "$APP_CONFIG" << EOF
# Application database configuration
# Generated by deploy pipeline
DB_HOST=${RDS_ENDPOINT}
DB_PORT=${DB_PORT}
DB_NAME=${DB_NAME}
DB_USER=${DB_USER}
EOF

success "Correct config written to $APP_CONFIG"

# Step 2 - Back up the correct config
cp "$APP_CONFIG" "$BACKUP_CONFIG"
info "Backup saved to $BACKUP_CONFIG"

# Step 3 - Inject a broken endpoint (nonexistent host)
# Replace the real endpoint with a plausible-looking but wrong hostname
WRONG_ENDPOINT=$(echo "$RDS_ENDPOINT" | sed 's/\.[a-z0-9]*\.rds\.amazonaws\.com$/.XxXxXxXx.rds.amazonaws.com/')

info "Injecting wrong endpoint into $APP_CONFIG..."
sed -i.bak "s|DB_HOST=.*|DB_HOST=${WRONG_ENDPOINT}|" "$APP_CONFIG"

# Verify the injection
CURRENT_HOST=$(grep "^DB_HOST=" "$APP_CONFIG" | cut -d= -f2)
if [[ "$CURRENT_HOST" == "$WRONG_ENDPOINT" ]]; then
  success "Endpoint in config is now: $WRONG_ENDPOINT"
else
  fail "Injection failed. Config still has: $CURRENT_HOST"
  exit 1
fi

echo ""
echo "========================================"
echo "  INJECTION COMPLETE"
echo "========================================"
echo ""
echo "  Scenario: Wrong Endpoint"
echo "  The application config at $APP_CONFIG"
echo "  now points to a nonexistent host."
echo ""
echo "  Application startup will fail with a DNS error."
echo "  The real RDS instance is still running fine."
echo ""
echo "  Now open: survive/02-wrong-endpoint/runbook.md"
echo "========================================"
