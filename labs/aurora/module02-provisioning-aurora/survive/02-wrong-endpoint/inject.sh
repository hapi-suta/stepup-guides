#!/usr/bin/env bash
# survive/02-wrong-endpoint/inject.sh
# Writes a connection script that uses the reader endpoint for write operations.
# This simulates an application misconfiguration where writes go to a read-only endpoint.
#
# Required environment variables:
#   CLUSTER_ID       - Aurora cluster identifier (default: devops-lab-cluster)
#   REGION           - AWS region (default: us-east-1)
#
# Usage:
#   export CLUSTER_ID=devops-lab-cluster
#   export REGION=us-east-1
#   bash inject.sh

set -euo pipefail

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
CLUSTER_ID="${CLUSTER_ID:-devops-lab-cluster}"
REGION="${REGION:-us-east-1}"
APP_CONFIG="/tmp/devops-app-config.env"
APP_SCRIPT="/tmp/devops-app-writer.sh"
BACKUP_CONFIG="/tmp/devops-app-config-backup-02.env"

echo ""
echo "========================================"
echo "  INJECT: Wrong Endpoint"
echo "========================================"
echo ""

# ---------------------------------------------------------------------------
# Step 1 - Get the cluster endpoints
# ---------------------------------------------------------------------------
echo "[INFO]  Looking up cluster endpoints..."

WRITER_EP=$(aws rds describe-db-clusters \
  --db-cluster-identifier "$CLUSTER_ID" \
  --region "$REGION" \
  --query "DBClusters[0].Endpoint" \
  --output text 2>/dev/null)

READER_EP=$(aws rds describe-db-clusters \
  --db-cluster-identifier "$CLUSTER_ID" \
  --region "$REGION" \
  --query "DBClusters[0].ReaderEndpoint" \
  --output text 2>/dev/null)

if [[ -z "$WRITER_EP" || "$WRITER_EP" == "None" ]]; then
  echo "[FAIL]  Could not find writer endpoint for cluster $CLUSTER_ID"
  exit 1
fi

if [[ -z "$READER_EP" || "$READER_EP" == "None" ]]; then
  echo "[FAIL]  Could not find reader endpoint for cluster $CLUSTER_ID"
  echo "        Make sure the cluster has at least one reader instance."
  exit 1
fi

echo "[PASS]  Writer endpoint: $WRITER_EP"
echo "[PASS]  Reader endpoint: $READER_EP"

# ---------------------------------------------------------------------------
# Step 2 - Write the correct config first (for backup)
# ---------------------------------------------------------------------------
echo "[INFO]  Writing correct config to $BACKUP_CONFIG..."

cat > "$BACKUP_CONFIG" << EOF
# Application database configuration - CORRECT
# Generated by deploy pipeline
DB_HOST=${WRITER_EP}
DB_PORT=5432
DB_NAME=devopsdb
DB_USER=clusteradmin
EOF

echo "[PASS]  Backup saved"

# ---------------------------------------------------------------------------
# Step 3 - Write the BROKEN config (reader endpoint for writes)
# ---------------------------------------------------------------------------
echo "[INFO]  Writing broken config to $APP_CONFIG..."

cat > "$APP_CONFIG" << EOF
# Application database configuration
# Generated by deploy pipeline
DB_HOST=${READER_EP}
DB_PORT=5432
DB_NAME=devopsdb
DB_USER=clusteradmin
EOF

echo "[PASS]  Broken config written (uses reader endpoint for DB_HOST)"

# ---------------------------------------------------------------------------
# Step 4 - Create a simulated app script that tries to write
# ---------------------------------------------------------------------------
echo "[INFO]  Creating simulated app script at $APP_SCRIPT..."

cat > "$APP_SCRIPT" << 'SCRIPT_EOF'
#!/usr/bin/env bash
# Simulated application that writes to the database
# This script sources the config and tries to INSERT data.
set -euo pipefail

source /tmp/devops-app-config.env

echo "Connecting to: $DB_HOST"
echo "Attempting to write order data..."

PGPASSWORD="${PGPASSWORD:-}" psql \
  -h "$DB_HOST" \
  -U "$DB_USER" \
  -d "$DB_NAME" \
  -p "$DB_PORT" \
  -c "INSERT INTO endpoint_test (source) VALUES ('app-write-$(date +%s)');" 2>&1

echo "Write completed successfully."
SCRIPT_EOF

chmod +x "$APP_SCRIPT"
echo "[PASS]  App script created"

# ---------------------------------------------------------------------------
# Step 5 - Verify the injection
# ---------------------------------------------------------------------------
CONFIGURED_HOST=$(grep "^DB_HOST=" "$APP_CONFIG" | cut -d= -f2)

if [[ "$CONFIGURED_HOST" == "$READER_EP" ]]; then
  echo "[PASS]  Config now points to reader endpoint (wrong for writes)"
else
  echo "[FAIL]  Injection failed. Config has: $CONFIGURED_HOST"
  exit 1
fi

echo ""
echo "========================================"
echo "  INJECTION COMPLETE"
echo "========================================"
echo ""
echo "  Scenario: Wrong Endpoint"
echo "  The application config at $APP_CONFIG"
echo "  points to the READER endpoint instead of the WRITER endpoint."
echo ""
echo "  The app script at $APP_SCRIPT will fail with"
echo "  read-only transaction errors when it tries to write."
echo ""
echo "  Try running: bash $APP_SCRIPT"
echo "  You should see the error."
echo ""
echo "  Now open: survive/02-wrong-endpoint/runbook.md"
echo "========================================"
